function createDefaultNumberingFormat(documentType: string, prefix: string): NumberingFormat {
  return {
    id: `default-${documentType}`,
    document_type: documentType,
    prefix,
    include_year: true,
    separator: "-",
    padding: 4,
    next_number: 1,
    is_active: true
  };
}

function createDefaultOption(
  optionGroup: string,
  optionKey: string,
  label: string,
  sortOrder: number
): ConfigurableOption {
  return {
    id: `default-${optionGroup}-${optionKey}`,
    option_group: optionGroup,
    option_key: optionKey,
    label,
    sort_order: sortOrder,
    is_active: true
  };
}

export function resolveCompanySettings(
  settings?: Partial<CompanySettings> | null
): EffectiveCompanySettings {
  return {
    company_name: settings?.company_name || DEFAULT_COMPANY_SETTINGS.company_name,
    legal_name: settings?.legal_name || "",
    email: settings?.email || "",
    phone: settings?.phone || "",
    website: settings?.website || "",
    address: settings?.address || "",
    gst_number: settings?.gst_number || "",
    pan_number: settings?.pan_number || "",
    logo_url: settings?.logo_url || DEFAULT_COMPANY_SETTINGS.logo_url,
    primary_color: settings?.primary_color || DEFAULT_COMPANY_SETTINGS.primary_color,
    secondary_color: settings?.secondary_color || DEFAULT_COMPANY_SETTINGS.secondary_color,
    currency: settings?.currency || DEFAULT_COMPANY_SETTINGS.currency,
    default_tax_percentage:
      settings?.default_tax_percentage ?? DEFAULT_COMPANY_SETTINGS.default_tax_percentage,
    bank_details: settings?.bank_details || "",
    authorized_signatory_name: settings?.authorized_signatory_name || "",
    default_footer_text:
      settings?.default_footer_text || DEFAULT_COMPANY_SETTINGS.default_footer_text
  };
}

function cacheCompanySettings(settings: EffectiveCompanySettings) {
  if (typeof window !== "undefined") {
    window.localStorage.setItem(COMPANY_SETTINGS_CACHE_KEY, JSON.stringify(settings));
  }
}

export const settingsService = {
  async uploadCompanyLogo(file: File) {
    const allowed = ["image/png", "image/jpeg", "image/webp", "image/svg+xml"];
    if (!allowed.includes(file.type)) throw new Error("Use a PNG, JPG, WebP, or SVG logo.");
    if (file.size > 2 * 1024 * 1024) throw new Error("Logo must be 2 MB or smaller.");
    if (!isSupabaseConfigured) {
      const dataUrl = await new Promise<string>((resolve, reject) => { const reader = new FileReader(); reader.onload = () => resolve(String(reader.result)); reader.onerror = reject; reader.readAsDataURL(file); });
      await this.saveCompanySettings({ logo_url: dataUrl });
      return dataUrl;
    }
    const extension = file.name.split(".").pop()?.toLowerCase().replace(/[^a-z0-9]/g, "") || "png";
    const path = `company/${Date.now()}-${crypto.randomUUID()}.${extension}`;
    const client = requireSupabase();
    const { error } = await client.storage.from("brand-assets").upload(path, file, { cacheControl: "31536000", upsert: false, contentType: file.type });
    if (error) throw error;
    const { data } = client.storage.from("brand-assets").getPublicUrl(path);
    await this.saveCompanySettings({ logo_url: data.publicUrl });
    return data.publicUrl;
  },
  async getCompanySettings() {
    if (!isSupabaseConfigured) {
      const settings = readDemoRecords<CompanySettings>(COMPANY_KEY)[0] ?? null;
      cacheCompanySettings(resolveCompanySettings(settings));
      return settings;
    }
    const { data, error } = await requireSupabase().from("company_settings").select("*").limit(1).maybeSingle();
    if (error) throw error;
    cacheCompanySettings(resolveCompanySettings(data as CompanySettings | null));
    return data as CompanySettings | null;
  },
  async saveCompanySettings(data: Partial<CompanySettings>) {
    if (!isSupabaseConfigured) {
      const now = new Date().toISOString();
      const current = readDemoRecords<CompanySettings>(COMPANY_KEY)[0];
      const record = { ...current, ...data, id: current?.id ?? crypto.randomUUID(), created_at: current?.created_at ?? now, updated_at: now } as CompanySettings;
      writeDemoRecords(COMPANY_KEY, [record]);
      cacheCompanySettings(resolveCompanySettings(record));
      return record;
    }
    const current = await this.getCompanySettings();
    const query = current
      ? requireSupabase().from("company_settings").update({ ...data, updated_at: new Date().toISOString() }).eq("id", current.id)
      : requireSupabase().from("company_settings").insert(data);
    const { data: record, error } = await query.select().single();
    if (error) throw error;
    cacheCompanySettings(resolveCompanySettings(record as CompanySettings));
    return record as CompanySettings;
  },
  async getEffectiveCompanySettings() {
    return resolveCompanySettings(await this.getCompanySettings());
  },
  async getNumberingFormats() {
    if (!isSupabaseConfigured) {
      const records = readDemoRecords<NumberingFormat>(NUMBERING_KEY);
      return mergeDefaultNumberingFormats(records);
    }

    const { data, error } = await requireSupabase()
      .from("numbering_formats")
      .select("*")
      .order("document_type", { ascending: true });

    if (error) throw error;
    return mergeDefaultNumberingFormats(data as NumberingFormat[]);
  },
  async saveNumberingFormat(documentType: string, data: Partial<NumberingFormat>) {
    const existing = (await this.getNumberingFormats()).find(
      (format) => format.document_type === documentType
    );
    const payload = {
      document_type: documentType,
      prefix: String(data.prefix ?? existing?.prefix ?? documentType.toUpperCase()).trim(),
      include_year: data.include_year ?? existing?.include_year ?? true,
      separator: String(data.separator ?? existing?.separator ?? "-").slice(0, 3) || "-",
      padding: Number(data.padding ?? existing?.padding ?? 4),
      next_number: Number(data.next_number ?? existing?.next_number ?? 1),
      is_active: data.is_active ?? existing?.is_active ?? true
    };

    if (!isSupabaseConfigured) {
      const records = readDemoRecords<NumberingFormat>(NUMBERING_KEY);
      const now = new Date().toISOString();
      const record = {
        ...existing,
        ...payload,
        id: existing?.id?.startsWith("default-") ? crypto.randomUUID() : existing?.id ?? crypto.randomUUID(),
        created_at: existing?.created_at ?? now,
        updated_at: now
      } as NumberingFormat;
      writeDemoRecords(NUMBERING_KEY, [
        record,
        ...records.filter((item) => item.document_type !== documentType)
      ]);
      return record;
    }

    const table = requireSupabase().from("numbering_formats");
    const query = existing && !existing.id.startsWith("default-")
      ? table.update({ ...payload, updated_at: new Date().toISOString() }).eq("id", existing.id)
      : table.insert(payload);
    const { data: record, error } = await query.select().single();
    if (error) throw error;
    return record as NumberingFormat;
  },
  async getNumberingPrefix(documentType: string, fallbackPrefix: string) {
    const format = (await this.getNumberingFormats()).find(
      (item) => item.document_type === documentType && item.is_active
    );
    return format?.prefix?.trim() || fallbackPrefix;
  },
  async listConfigurableOptions() {
    if (!isSupabaseConfigured) {
      return mergeDefaultOptions(readDemoRecords<ConfigurableOption>(OPTIONS_KEY));
    }

    const { data, error } = await requireSupabase()
      .from("configurable_options")
      .select("*")
      .order("option_group", { ascending: true })
      .order("sort_order", { ascending: true });

    if (error) throw error;
    return mergeDefaultOptions(data as ConfigurableOption[]);
  },
  async createConfigurableOption(data: Omit<ConfigurableOption, "id">) {
    if (!isSupabaseConfigured) {
      const now = new Date().toISOString();
      const record = { id: crypto.randomUUID(), ...data, created_at: now, updated_at: now };
      writeDemoRecords(OPTIONS_KEY, [record, ...readDemoRecords<ConfigurableOption>(OPTIONS_KEY)]);
      return record;
    }

    const { data: record, error } = await requireSupabase()
      .from("configurable_options")
      .insert(data)
      .select()
      .single();
    if (error) throw error;
    return record as ConfigurableOption;
  },
  async listMaster(table: string) {
    if (!isSupabaseConfigured) return readDemoRecords<MasterRecord>(`demo-${table}`);
    const { data, error } = await requireSupabase().from(table).select("*").order("created_at", { ascending: false });
    if (error) throw error;
    return data as MasterRecord[];
  },
  async createMaster(table: string, data: Record<string, unknown>) {
    if (!isSupabaseConfigured) {
      const key = `demo-${table}`;
      const now = new Date().toISOString();
      const record = { id: crypto.randomUUID(), ...data, created_at: now, updated_at: now };
      writeDemoRecords(key, [record, ...readDemoRecords<Record<string, unknown>>(key)]);
      return record;
    }
    const { data: record, error } = await requireSupabase().from(table).insert(data).select().single();
    if (error) throw error;
    return record;
  }
};

function mergeDefaultNumberingFormats(records: NumberingFormat[]) {
  const byType = new Map(records.map((record) => [record.document_type, record]));
  DEFAULT_NUMBERING_FORMATS.forEach((record) => {
    if (!byType.has(record.document_type)) {
      byType.set(record.document_type, record);
    }
  });
  return Array.from(byType.values());
}

function mergeDefaultOptions(records: ConfigurableOption[]) {
  const key = (record: ConfigurableOption) => `${record.option_group}:${record.option_key}`;
  const byKey = new Map(records.map((record) => [key(record), record]));
  DEFAULT_CONFIGURABLE_OPTIONS.forEach((record) => {
    if (!byKey.has(key(record))) {
      byKey.set(key(record), record);
    }
  });
  return Array.from(byKey.values()).sort((a, b) =>
    `${a.option_group}-${a.sort_order ?? 0}`.localeCompare(`${b.option_group}-${b.sort_order ?? 0}`)
  );
}
